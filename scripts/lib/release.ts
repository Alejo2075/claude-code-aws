import { cpSync, existsSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { findTemplateMarkers } from "./checks.js";
import {
  type Catalog,
  catalogPath,
  isReleased,
  listPlugins,
  type PluginInfo,
  readJson,
  REPO_ROOT,
  writeJson,
} from "./workspace.js";

/** Plugin paths copied into the release tree. Everything else (src, tests, evals, configs) stays on main. */
export const RELEASE_ALLOWLIST = [
  ".claude-plugin",
  "dist",
  "skills",
  "agents",
  "commands",
  "hooks",
  "output-styles",
  "monitors",
  "assets",
  ".mcp.json",
  ".lsp.json",
  "settings.json",
  "README.md",
  "CHANGELOG.md",
];

export interface ReleaseOptions {
  repoRoot?: string;
  pluginsRoot?: string;
  outDir: string;
  /** Include 0.0.0 plugins and tolerate template markers; used by the pipeline self-test only. */
  selfTest?: boolean;
}

export interface ReleaseTree {
  outDir: string;
  plugins: PluginInfo[];
}

const RELEASE_README = `# Release branch

This branch is generated by the release workflow from \`main\`. Do not edit it or open pull requests against it.

Install plugins with:

\`\`\`text
/plugin marketplace add Alejo2075/claude-code-aws
\`\`\`

Sources, documentation, and contribution guidelines are on the \`main\` branch.
`;

export function buildReleaseTree(options: ReleaseOptions): ReleaseTree {
  const repoRoot = options.repoRoot ?? REPO_ROOT;
  const pluginsRoot = options.pluginsRoot ?? join(repoRoot, "plugins");
  const plugins = listPlugins(pluginsRoot).filter(
    (plugin) => options.selfTest === true || isReleased(plugin),
  );
  const problems: string[] = [];
  for (const plugin of plugins) {
    if (!existsSync(join(plugin.dir, "dist")) && existsSync(join(plugin.dir, "src", "entries"))) {
      problems.push(`${plugin.name}: dist/ is missing; run pnpm build first`);
    }
    for (const hit of findTemplateMarkers(plugin.dir))
      problems.push(`${plugin.name}: template marker in ${hit}`);
  }
  if (problems.length > 0 && options.selfTest !== true) {
    throw new Error(`Release tree refused:\n  ${problems.join("\n  ")}`);
  }

  rmSync(options.outDir, { recursive: true, force: true });
  mkdirSync(join(options.outDir, ".claude-plugin"), { recursive: true });
  for (const plugin of plugins) {
    const target = join(options.outDir, "plugins", plugin.name);
    mkdirSync(target, { recursive: true });
    for (const item of RELEASE_ALLOWLIST) {
      const source = join(plugin.dir, item);
      if (existsSync(source))
        cpSync(source, join(target, item), { recursive: true, dereference: false });
    }
    cpSync(join(repoRoot, "LICENSE"), join(target, "LICENSE"));
  }

  const mainCatalog = readJson<Catalog>(catalogPath(repoRoot));
  // On the release branch, plugins live next to the catalog, so entries use relative paths.
  const releaseCatalog: Catalog = {
    ...mainCatalog,
    plugins: plugins.map((plugin) => {
      const entry = mainCatalog.plugins.find((candidate) => candidate.name === plugin.name);
      return {
        ...(entry ?? { name: plugin.name, description: plugin.manifest.description ?? "" }),
        source: `./plugins/${plugin.name}`,
      };
    }),
  };
  writeJson(catalogPath(options.outDir), releaseCatalog);
  cpSync(join(repoRoot, "LICENSE"), join(options.outDir, "LICENSE"));
  writeFileSync(join(options.outDir, "README.md"), RELEASE_README);
  return { outDir: options.outDir, plugins: listPlugins(join(options.outDir, "plugins")) };
}
