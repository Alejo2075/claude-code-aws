// GitHub Actions deployment with OIDC and no long-lived keys. The generated role may only assume the
// CDK bootstrap roles, which are the roles `cdk deploy` itself uses. The deploy job runs in a GitHub
// environment, so protection rules (required reviewers) approve every production deployment.
export interface PipelineInput {
  account: string;
  region: string;
  repo: string;
  environment: string;
  branch: string;
  qualifier: string;
}

const ACCOUNT = /^\d{12}$/;
const REGION = /^[a-z]{2}(-[a-z]+)+-\d$/;
const REPO = /^[A-Za-z0-9_.-]{1,39}\/[A-Za-z0-9_.-]{1,100}$/;
const NAME = /^[A-Za-z0-9_.-]{1,60}$/;
const QUALIFIER = /^[a-z0-9]{1,10}$/;

export interface PipelineFile {
  path: string;
  content: string;
}

export function validatePipeline(input: PipelineInput): string | null {
  if (!ACCOUNT.test(input.account)) return "--account must be a 12-digit account id.";
  if (!REGION.test(input.region)) return "--region is not a valid region name.";
  if (!REPO.test(input.repo)) return "--repo must look like owner/name.";
  if (!NAME.test(input.environment))
    return "--environment may only contain letters, digits, dot, dash and underscore.";
  if (!NAME.test(input.branch))
    return "--branch may only contain letters, digits, dot, dash and underscore.";
  if (!QUALIFIER.test(input.qualifier))
    return "--qualifier must be the CDK bootstrap qualifier (default hnb659fds).";
  return null;
}

export function pipelineFiles(input: PipelineInput): PipelineFile[] {
  const roleName = "github-cdk-deploy";
  const roles = ["deploy", "file-publishing", "image-publishing", "lookup"].map(
    (kind) =>
      `arn:aws:iam::${input.account}:role/cdk-${input.qualifier}-${kind}-role-${input.account}-${input.region}`,
  );
  const trust = {
    Version: "2012-10-17",
    Statement: [
      {
        Effect: "Allow",
        Principal: {
          Federated: `arn:aws:iam::${input.account}:oidc-provider/token.actions.githubusercontent.com`,
        },
        Action: "sts:AssumeRoleWithWebIdentity",
        Condition: {
          StringEquals: { "token.actions.githubusercontent.com:aud": "sts.amazonaws.com" },
          StringLike: {
            "token.actions.githubusercontent.com:sub": `repo:${input.repo}:environment:${input.environment}`,
          },
        },
      },
    ],
  };
  const policy = {
    Version: "2012-10-17",
    Statement: [{ Effect: "Allow", Action: "sts:AssumeRole", Resource: roles }],
  };
  const workflow = `# Generated by aws-deploy. Review it before use.
# Deployment authenticates with GitHub OIDC: there are no AWS access keys in this repository.
# The role (${roleName}) can only assume the CDK bootstrap roles; see iam/.
# The deploy job runs in the "${input.environment}" GitHub environment: add required reviewers to it
# (Settings -> Environments) so every deployment is approved by a person.
name: deploy
on:
  pull_request:
  push:
    branches: [${input.branch}]
permissions:
  contents: read
jobs:
  check:
    # Pull requests: build and test without any AWS credentials.
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1 # v7.0.1
      - uses: actions/setup-node@949feb2413d6458794dcd2491c4babbbce0c15c1 # v7.1.0
        with:
          node-version: 22
          cache: npm
      - run: npm ci
      - run: npm test
      - run: npx cdk synth --no-lookups --quiet
  deploy:
    if: github.event_name == 'push'
    needs: check
    runs-on: ubuntu-latest
    environment: ${input.environment}
    permissions:
      id-token: write
      contents: read
    concurrency:
      group: deploy-${input.environment}
      cancel-in-progress: false
    steps:
      - uses: actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1 # v7.0.1
      - uses: actions/setup-node@949feb2413d6458794dcd2491c4babbbce0c15c1 # v7.1.0
        with:
          node-version: 22
          cache: npm
      - run: npm ci
      - uses: aws-actions/configure-aws-credentials@e1253824e5c10ff9df46874f81ed3ec929e19cfd # v6.3.0
        with:
          role-to-assume: arn:aws:iam::${input.account}:role/${roleName}
          aws-region: ${input.region}
      # "broadening" stops the deployment when it would add permissions, so a person reviews those.
      - run: npx cdk deploy --all --require-approval broadening
`;
  return [
    { path: ".github/workflows/deploy.yml", content: workflow },
    { path: "iam/github-oidc-trust.json", content: `${JSON.stringify(trust, null, 2)}\n` },
    { path: "iam/github-deploy-policy.json", content: `${JSON.stringify(policy, null, 2)}\n` },
  ];
}
