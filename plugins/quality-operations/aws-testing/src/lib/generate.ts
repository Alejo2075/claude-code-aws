// Deterministic test generators. They write nothing unless asked, never overwrite, and produce files
// that need no AWS. The skill adds domain-specific cases on top of these.
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, posix, relative, resolve, sep } from "node:path";

import { resourcesOfType, type Template } from "@claude-code-aws/template-analysis";
import { isInside } from "@claude-code-aws/tool-runner";

import { baseEvent, fixture, isKind, type Kind, KINDS } from "./fixtures.js";

export interface GeneratedFile {
  path: string;
  content: string;
}

const NAME = /^[A-Za-z][A-Za-z0-9_-]{0,60}$/;

/**
 * Assertions about policy, read from the synthesized template (`cdk.out`), not a snapshot of values:
 * they keep holding while the app changes, and fail when a safeguard is removed. Only the checks
 * for resource types the template contains are emitted.
 */
export function cdkAssertionsTest(
  stack: string,
  templatePath: string,
  template: Template,
  testPath: string,
): GeneratedFile | { error: string } {
  if (!NAME.test(stack))
    return { error: "The stack name may only contain letters, digits, dash and underscore." };
  const has = (...types: string[]): boolean => resourcesOfType(template, ...types).length > 0;
  const from = posix.relative(posix.dirname(testPath), templatePath.split(sep).join("/"));
  const checks: string[] = [];
  if (has("AWS::SQS::Queue")) {
    checks.push(`  it("gives every queue that is not a dead-letter queue a redrive policy", () => {
    const queues = template.findResources("AWS::SQS::Queue");
    const targets = new Set(
      Object.values(queues).flatMap((queue) => {
        const arn = (queue.Properties?.RedrivePolicy as { deadLetterTargetArn?: { "Fn::GetAtt"?: string[] } } | undefined)?.deadLetterTargetArn;
        return arn?.["Fn::GetAtt"]?.[0] === undefined ? [] : [arn["Fn::GetAtt"][0]];
      }),
    );
    for (const [id, queue] of Object.entries(queues)) {
      if (!targets.has(id)) expect(queue.Properties?.RedrivePolicy, \`\${id} needs a dead-letter queue\`).toBeDefined();
    }
  });
`);
  }
  if (has("AWS::Lambda::Function")) {
    checks.push(`  it("sets an explicit timeout on every function", () => {
    for (const [id, fn] of Object.entries(template.findResources("AWS::Lambda::Function"))) {
      expect(fn.Properties?.Timeout, \`\${id} relies on the default timeout\`).toBeDefined();
    }
  });
`);
  }
  if (has("AWS::DynamoDB::Table")) {
    checks.push(`  it("enables point-in-time recovery on every table", () => {
    for (const [id, table] of Object.entries(template.findResources("AWS::DynamoDB::Table"))) {
      expect(table.Properties?.PointInTimeRecoverySpecification?.PointInTimeRecoveryEnabled, id).toBe(true);
    }
  });
`);
  }
  if (has("AWS::DynamoDB::Table", "AWS::S3::Bucket", "AWS::Cognito::UserPool")) {
    checks.push(`  it("retains the data of stateful resources when the stack is deleted", () => {
    for (const type of ["AWS::DynamoDB::Table", "AWS::S3::Bucket", "AWS::Cognito::UserPool"]) {
      for (const [id, resource] of Object.entries(template.findResources(type))) {
        expect(resource.DeletionPolicy, \`\${id} (\${type})\`).toBe("Retain");
      }
    }
  });
`);
  }
  if (has("AWS::S3::Bucket")) {
    checks.push(`  it("blocks public access on every bucket", () => {
    for (const [id, bucket] of Object.entries(template.findResources("AWS::S3::Bucket"))) {
      const block = bucket.Properties?.PublicAccessBlockConfiguration ?? {};
      for (const key of ["BlockPublicAcls", "BlockPublicPolicy", "IgnorePublicAcls", "RestrictPublicBuckets"]) {
        expect(block[key], \`\${id} \${key}\`).toBe(true);
      }
    }
  });
`);
  }
  checks.push(`  it("never allows every action on every resource", () => {
    const documents = [
      ...Object.values(template.findResources("AWS::IAM::Policy")).map((policy) => policy.Properties?.PolicyDocument),
      ...Object.values(template.findResources("AWS::IAM::ManagedPolicy")).map((policy) => policy.Properties?.PolicyDocument),
    ];
    for (const document of documents) {
      for (const statement of [document?.Statement ?? []].flat()) {
        const actions = [statement.Action ?? []].flat();
        const resources = [statement.Resource ?? []].flat();
        const everything = statement.Effect === "Allow" && actions.includes("*") && resources.includes("*");
        expect(everything, "a policy statement allows * on *").toBe(false);
      }
    }
  });
`);
  const content = `// Generated by aws-testing. These assertions check policy, not values, so they keep holding while the
// app changes. Run \`cdk synth\` first: they read ${templatePath}.
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { Template } from "aws-cdk-lib/assertions";
import { describe, expect, it } from "vitest";

describe("${stack} template", () => {
  const file = fileURLToPath(new URL(${JSON.stringify(from)}, import.meta.url));
  const template = Template.fromJSON(JSON.parse(readFileSync(file, "utf8")));

${checks.join("\n")}});
`;
  return { path: testPath, content };
}

const HANDLER_ASSERTIONS: Partial<Record<Kind, string>> = {
  sqs: `  it("reports only the failed record of a mixed batch", async () => {
    const event = fixture("batch-one-bad");
    const response = await handler(event);
    expect(response.batchItemFailures).toHaveLength(1);
    expect(response.batchItemFailures[0].itemIdentifier).toBe(event.Records[2].messageId);
  });

  it("is idempotent when the same message is delivered twice", async () => {
    const event = fixture("duplicate");
    const first = await handler(event);
    const second = await handler(event);
    expect(second).toEqual(first);
  });

  it("accepts an empty batch", async () => {
    expect(await handler(fixture("empty-records"))).toEqual({ batchItemFailures: [] });
  });`,
  "apigw-http-v2": `  it("answers with a valid proxy response", async () => {
    const response = await handler(fixture());
    expect(Number.isInteger(response.statusCode)).toBe(true);
    expect(typeof (response.body ?? "")).toBe("string");
  });

  it("rejects a malformed body with a 4xx, not a 5xx", async () => {
    const response = await handler(fixture("malformed-body"));
    expect(response.statusCode).toBeGreaterThanOrEqual(400);
    expect(response.statusCode).toBeLessThan(500);
  });

  it("does not trust a request without authorizer claims", async () => {
    const response = await handler(fixture("no-auth"));
    expect([401, 403]).toContain(response.statusCode);
  });`,
};

const literal = (value: unknown): string => JSON.stringify(value, null, 2);

/** A test skeleton for one handler, built on the event fixtures. Cases that need domain knowledge are marked TODO. */
export function handlerTest(
  root: string,
  handlerFile: string,
  kind: string,
  testPath: string,
  exportName = "handler",
): GeneratedFile | { error: string } {
  if (!isKind(kind))
    return { error: `Unknown event kind "${kind}". Choose one of: ${KINDS.join(", ")}.` };
  if (!/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(exportName))
    return { error: "The export name is not a valid identifier." };
  const target = resolve(root, handlerFile);
  if (!isInside(root, target)) return { error: "The handler file is outside the project." };
  const importPath = posix.relative(
    posix.dirname(testPath),
    relative(root, target).split(sep).join("/"),
  );
  const specifier = importPath.startsWith(".") ? importPath : `./${importPath}`;
  const assertions = HANDLER_ASSERTIONS[kind] ?? "";
  // Embed exactly the variants the assertions use, so the generated file stands on its own.
  const used = [
    ...new Set(
      [...assertions.matchAll(/fixture\("([a-z0-9-]+)"\)/g)].map((match) => match[1] ?? ""),
    ),
  ];
  const variants = Object.fromEntries(used.map((name) => [name, fixture(kind, name)]));
  const content = `// Generated by aws-testing for the "${kind}" event. The fixtures follow the AWS documentation; extend
// the cases with the behavior only you know (TODO markers).
import { describe, expect, it } from "vitest";

import { ${exportName} as handler } from ${JSON.stringify(specifier)};

const base = ${literal(baseEvent(kind))};
const variants: Record<string, unknown> = ${literal(variants)};

// eslint-disable-next-line @typescript-eslint/no-explicit-any
function fixture(variant?: string): any {
  return structuredClone(variant === undefined ? base : variants[variant]);
}

describe(${JSON.stringify(handlerFile)}, () => {
  it("handles the documented event without throwing", async () => {
    await expect(Promise.resolve(handler(fixture(), {} as never, () => undefined))).resolves.not.toThrow();
  });
${assertions === "" ? "" : `\n${assertions}\n`}
  it.todo("TODO: covers the business rule that decides success or failure");
  it.todo("TODO: verifies each call this handler makes to an AWS service, with the exact parameters");
});
`;
  return { path: testPath, content };
}

export interface WriteOutcome {
  written: string[];
  skipped: string[];
}

export function writeFiles(root: string, files: readonly GeneratedFile[]): WriteOutcome {
  const outcome: WriteOutcome = { written: [], skipped: [] };
  for (const file of files) {
    const target = resolve(root, file.path);
    if (!isInside(root, target)) {
      outcome.skipped.push(file.path);
      continue;
    }
    mkdirSync(dirname(target), { recursive: true });
    try {
      writeFileSync(target, file.content, { flag: "wx" });
      outcome.written.push(file.path);
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== "EEXIST") throw error;
      outcome.skipped.push(file.path);
    }
  }
  return outcome;
}
